#!/usr/bin/env node
// Build manifest.json for the CNKI Research Portable distribution.
//
//   node tools/build_manifest.mjs [--check]
//
// The manifest is the single source of truth for the static package test: it
// records the distribution identity, the frozen v1.0 baseline, the pinned
// dependency set, the compatibility matrix, and a SHA-256 + byte size for every
// shipped payload file. `--check` recomputes the hashes and fails when the
// working tree has drifted from a committed manifest.json.
//
// Deterministic by construction: files are sorted, JSON is emitted with 2-space
// indentation, and no timestamp is written unless --stamp is passed.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');

const argv = process.argv.slice(2);
const checkOnly = argv.includes('--check');
// Directories that are never part of the release payload.
//   _scratch           developer recon and probes
//   _portable          install state and backups, written at install time
//   docs/test-evidence generated by tests/run_all.ps1 -- excluding it keeps the
//                      documented test command from dirtying manifest.json
const EXCLUDED_DIRS = new Set([
  '_scratch',
  'dist',
  '_portable',
  'node_modules',
  '__pycache__',
  '.venv',
  '.git',
  'test-evidence',
]);
const EXCLUDED_FILES = new Set([
  'manifest.json',
  '.DS_Store',
  'Thumbs.db',
  // Written by `portable.ps1 -Action install`. It records this machine's resolved
  // interpreter and CNKI profile name, so it must never ship.
  'portable.runtime.json',
  // The *release* manifest (tools/build_release_manifest.mjs). It records the hash of
  // the built archive, so including it in the payload would be circular: every build
  // would change a payload file and invalidate itself.
  'RELEASE_MANIFEST.json',
]);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') && entry.name !== '.gitignore') continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (EXCLUDED_DIRS.has(entry.name)) continue;
      walk(full, out);
    } else if (entry.isFile()) {
      if (EXCLUDED_FILES.has(entry.name)) continue;
      out.push(full);
    }
  }
  return out;
}

function sha256(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}

function rel(file) {
  return relative(packageRoot, file).split(sep).join('/');
}

const files = walk(packageRoot).map((file) => {
  const bytes = statSync(file).size;
  return { path: rel(file), bytes, sha256: sha256(file) };
});

const readJson = (p) => JSON.parse(readFileSync(join(packageRoot, p), 'utf8'));
const version = readFileSync(join(packageRoot, 'VERSION'), 'utf8').trim();
const bundlePackage = readJson('bundle/cnki-research/package.json');
const baseline = readJson('docs/provenance/v1.0-bundle.sha256.json');
const upstreamSrc = readJson('docs/provenance/upstream-src.sha256.json');

const manifest = {
  schemaVersion: 1,
  distribution: {
    name: 'cnki-research-portable',
    title: 'CNKI Research Portable',
    version,
    license: 'GPL-3.0-only',
    platform: ['windows-x64'],
  },
  bundle: {
    name: bundlePackage.name,
    version: bundlePackage.version,
    presetId: 'cnki-research',
    presetName: 'CNKI Research',
    order: 5,
    entry: 'bundle/cnki-research',
    patch: 'bundle/cnki-research/cordis.patch.yml',
    mcpTools: [
      'easy-search',
      'advanced-search',
      'get-info-from-url',
      'get-info-by-detail',
      'list-journal',
      'search-issn',
      'login',
      'logout',
    ],
    mcpResources: ['profile://list'],
  },
  baseline: {
    description:
      'Frozen production baseline: the verified @local/dsh-cnki-research v1.0.0 bundle that the portable distribution is derived from. Read-only; never modified by this distribution.',
    sourcePinnedBy: 'SHA-256 of every file (see docs/provenance/v1.0-bundle.sha256.json)',
    files: baseline.map((entry) => ({ path: entry.path, bytes: entry.bytes, sha256: entry.sha256 })),
  },
  dependencies: {
    python: { minimum: '3.11', verified: '3.12.0', bundledWithDshVerified: '3.12.14' },
    uv: { version: '0.12.15', minimum: '0.7.0', source: 'https://github.com/astral-sh/uv' },
    cnkiMcp: {
      name: 'cnki-mcp',
      version: '0.1.1',
      license: 'GPL-3.0',
      repository: 'https://github.com/sepinetam/cnki-mcp',
      defaultSource: 'vendored',
      vendoredPath: 'upstream/cnki-mcp',
      pinnedBy: 'upstream/cnki-mcp/uv.lock (uv sync --frozen)',
      upstreamSourceFiles: upstreamSrc.length,
      pypi: {
        name: 'cnki-mcp',
        version: '0.1.1',
        wheel: 'cnki_mcp-0.1.1-py3-none-any.whl',
        wheelSha256: 'a43399eddb060d521359db90cade56263b55a28b77e05e71ccd27b5007dd20d1',
        sdist: 'cnki_mcp-0.1.1.tar.gz',
        sdistSha256: '1f6098b238b1eafb051984a90a61ff49612a677fa8035dfc60b0a9281460fa99',
      },
    },
    pythonPackages: {
      mcp: '1.30.0',
      playwright: '1.63.0',
    },
    playwrightBrowser: { chromium: '1243' },
    node: { required: false, note: 'only DSH Desktop itself needs Node; the portable runtime is Python-only' },
  },
  compatibility: {
    os: { verified: ['Windows 11 x64'], untested: ['Windows 10 x64', 'Linux', 'macOS'] },
    dshDesktopRange: '>=0.2.0-rc.2 <0.3.0',
    dshDesktopVerified: ['0.2.0-rc.2'],
    electronVerified: ['44.0.0'],
    dshPluginApi: [
      '@deepseek-ai/dsh-agent-preset',
      '@deepseek-ai/dsh-mcp-client',
      '@deepseek-ai/dsh-skill-filesystem',
      '@deepseek-ai/dsh-tool-skill',
      '@deepseek-ai/dsh-plugin-manager',
    ],
  },
  install: {
    entryPoint: 'tools/portable.ps1',
    dryRun: 'tools/portable.ps1 -Action check',
    defaultProfile: 'desktop',
    installSpec: 'link:<absolute path to bundle/cnki-research>',
    officialInstallPath: 'dsh plugin --profile <profile> add <spec>',
    restartRequired: false,
    pathIndependence: 'no absolute path is stored in bundle/cnki-research/cordis.patch.yml',
  },
  files,
};

const serialized = JSON.stringify(manifest, null, 2) + '\n';
const manifestPath = join(packageRoot, 'manifest.json');

if (checkOnly) {
  let current;
  try {
    current = readFileSync(manifestPath, 'utf8');
  } catch {
    console.error('manifest.json is missing; run: node tools/build_manifest.mjs');
    process.exit(1);
  }
  if (current !== serialized) {
    const a = JSON.parse(current);
    const mapA = new Map((a.files ?? []).map((f) => [f.path, f.sha256]));
    const mapB = new Map(files.map((f) => [f.path, f.sha256]));
    const problems = [];
    for (const [p, h] of mapB) {
      if (!mapA.has(p)) problems.push(`+ ${p} (not in manifest)`);
      else if (mapA.get(p) !== h) problems.push(`~ ${p} (hash changed)`);
    }
    for (const p of mapA.keys()) if (!mapB.has(p)) problems.push(`- ${p} (in manifest, missing on disk)`);
    console.error('manifest.json is stale relative to the working tree:');
    for (const line of problems.slice(0, 50)) console.error('  ' + line);
    if (problems.length > 50) console.error(`  ... and ${problems.length - 50} more`);
    process.exit(1);
  }
  console.log(`manifest.json is current: ${files.length} payload file(s), distribution ${version}`);
  process.exit(0);
}

writeFileSync(manifestPath, serialized);
console.log(`wrote manifest.json: ${files.length} payload file(s), distribution ${version}, bundle ${bundlePackage.name}@${bundlePackage.version}`);
